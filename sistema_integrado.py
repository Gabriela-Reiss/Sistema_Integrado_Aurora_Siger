import matplotlib.pyplot as plt

def gerar_grafico_previsoes(historico):
    avaliacao = avaliar_regressao(historico)

    if avaliacao is None:
        print("Não existem dados suficientes para gerar o gráfico.")
        return

    resultados = avaliacao["resultados"]

    horarios = [registro["horario"] for registro in resultados]
    valores_reais = [registro["valor_real"] for registro in resultados]
    valores_estimados = [registro["previsao"] for registro in resultados]

    plt.figure(figsize=(12, 5))

    plt.plot(
        horarios,
        valores_reais,
        marker="o",
        label="Geração real"
    )

    plt.plot(
        horarios,
        valores_estimados,
        marker="x",
        linestyle="--",
        label="Geração estimada"
    )

    plt.title("Comparação entre geração eólica real e estimada")
    plt.xlabel("Horário")
    plt.ylabel("Geração eólica (kWh por intervalo)")
    plt.xticks(rotation=45)
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

